#!/usr/bin/env python3
"""Writes the manifest for a Flathub submission of a release.

Flathub builds from published sources, not from a local folder: the
`type: dir` source of build-aux/flatpak/io.github.felixilgatto.Nuage.yml is
replaced by the git tag of the release, pinned to its commit.

Usage: scripts/flathub-manifest.py v0.1.0 [output directory]
       (default: target/flathub/; copy its two files to the Flathub repository)

Standard library only.
"""

import pathlib
import shutil
import subprocess
import sys

REPO = "https://github.com/felixilgatto/nuage.git"
MANIFEST = pathlib.Path("build-aux/flatpak/io.github.felixilgatto.Nuage.yml")
SOURCES = pathlib.Path("build-aux/flatpak/cargo-sources.json")


def main() -> int:
    if len(sys.argv) < 2 or not sys.argv[1].startswith("v"):
        print(__doc__.strip(), file=sys.stderr)
        return 2
    tag = sys.argv[1]
    out = pathlib.Path(sys.argv[2] if len(sys.argv) > 2 else "target/flathub")
    try:
        commit = subprocess.run(
            ["git", "rev-list", "-n", "1", tag], check=True, capture_output=True, text=True
        ).stdout.strip()
    except subprocess.CalledProcessError:
        print(f"no tag {tag}: create and push it first (git tag {tag}; git push origin {tag})", file=sys.stderr)
        return 1

    lines = MANIFEST.read_text().splitlines()
    result, i, replaced = [], 0, False
    while i < len(lines):
        line = lines[i]
        if line.strip() == "- type: dir":
            indent = line[: len(line) - len(line.lstrip())]
            result += [
                f"{indent}- type: git",
                f"{indent}  url: {REPO}",
                f"{indent}  tag: {tag}",
                f"{indent}  commit: {commit}",
            ]
            # Skip the dir source's own keys (path, skip and its list).
            i += 1
            while i < len(lines) and (
                lines[i].startswith(indent + "  ") and not lines[i].startswith(indent + "- ")
            ):
                i += 1
            replaced = True
            continue
        result.append(line)
        i += 1
    if not replaced:
        print(f"no `type: dir` source in {MANIFEST}", file=sys.stderr)
        return 1

    out.mkdir(parents=True, exist_ok=True)
    text = "\n".join(result) + "\n"
    text = text.replace(
        "# Build from the repository root:",
        f"# Flathub manifest of Nuage {tag}, generated by scripts/flathub-manifest.py.\n#\n# Build from the repository root:",
        1,
    )
    (out / MANIFEST.name).write_text(text)
    shutil.copy(SOURCES, out / SOURCES.name)
    print(f"wrote {out / MANIFEST.name} and {out / SOURCES.name} ({tag} = {commit[:12]})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
